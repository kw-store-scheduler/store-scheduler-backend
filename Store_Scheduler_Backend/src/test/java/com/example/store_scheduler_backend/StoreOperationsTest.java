package com.example.store_scheduler_backend;

import com.example.store_scheduler_backend.domain.Employee;
import com.example.store_scheduler_backend.domain.EmployeePermission;
import com.example.store_scheduler_backend.domain.EmploymentType;
import com.example.store_scheduler_backend.domain.Role;
import com.example.store_scheduler_backend.domain.Schedule;
import com.example.store_scheduler_backend.domain.Shift;
import com.example.store_scheduler_backend.domain.SkillWindowRequirement;
import com.example.store_scheduler_backend.domain.StaffPosition;
import com.example.store_scheduler_backend.domain.Store;
import com.example.store_scheduler_backend.domain.User;
import com.example.store_scheduler_backend.repository.EmployeeRepository;
import com.example.store_scheduler_backend.repository.ScheduleRepository;
import com.example.store_scheduler_backend.repository.ShiftRepository;
import com.example.store_scheduler_backend.repository.SkillWindowRequirementRepository;
import com.example.store_scheduler_backend.repository.StoreRepository;
import com.example.store_scheduler_backend.repository.UserRepository;
import com.example.store_scheduler_backend.security.JwtTokenProvider;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.ResultActions;
import org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalTime;
import java.time.YearMonth;
import java.util.List;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

// 매장 운영 설정(주기·자동 생성·연속 근무·5인 이상), 가산수당, 공휴일, 알림함, 근무자 목록, 역량 매칭, 내 정보 요약
@SpringBootTest
@AutoConfigureMockMvc
@Transactional
class StoreOperationsTest {

    private static final LocalDate TODAY = LocalDate.now();

    @Autowired MockMvc mockMvc;
    @Autowired JwtTokenProvider jwtTokenProvider;
    @Autowired UserRepository userRepository;
    @Autowired StoreRepository storeRepository;
    @Autowired EmployeeRepository employeeRepository;
    @Autowired ShiftRepository shiftRepository;
    @Autowired ScheduleRepository scheduleRepository;
    @Autowired SkillWindowRequirementRepository windowRepository;

    private Store store;
    private Employee yuna;
    private Employee jisu;

    @BeforeEach
    void setUp() {
        store = storeRepository.save(new Store("운영매장", null, userRepository.save(new User("owner", "pw", Role.MANAGER)), "OPERCD01"));
        Shift close = new Shift();
        close.setName("야간");
        close.setStartTime(LocalTime.of(22, 0));
        close.setEndTime(LocalTime.of(2, 0));
        close.setRequiredStaff(1);
        close.setStore(store);
        shiftRepository.save(close);
        yuna = employee("yuna", "유나", EmploymentType.PART_TIME);
        jisu = employee("jisu", "지수", EmploymentType.FULL_TIME);
        jisu.updatePosition(StaffPosition.MANAGER);
        schedule(yuna, TODAY, 22, 2);
    }

    @Test
    void 월간_자동_생성을_켜면_다음_기간과_생성_시각_희망_마감을_알려준다() throws Exception {
        as("owner", patch("/api/stores/{s}/settings", store.getId())
                .contentType("application/json")
                .content("{\"scheduleCycle\":\"MONTHLY\",\"autoGenerate\":true,\"autoGenerateDaysBefore\":2,\"autoGenerateHour\":9,"
                        + "\"maxConsecutiveDays\":5,\"fivePlusBusiness\":true}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.maxConsecutiveDays").value(5))
                .andExpect(jsonPath("$.scheduleCycle").value("MONTHLY"));

        LocalDate start = YearMonth.from(TODAY).plusMonths(1).atDay(1);
        as("yuna", get("/api/stores/{s}/schedules/plan", store.getId()))
                .andExpect(jsonPath("$.periodStart").value(start.toString()))
                .andExpect(jsonPath("$.periodEnd").value(YearMonth.from(start).atEndOfMonth().toString()))
                .andExpect(jsonPath("$.generateAt").value(start.minusDays(2) + "T09:00:00"))
                .andExpect(jsonPath("$.preferenceDeadline").value(start.minusDays(5).toString()));
        as("owner", patch("/api/stores/{s}/settings", store.getId())
                .contentType("application/json").content("{\"maxConsecutiveDays\":7}"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void 상시_5인_이상이면_야간_근무에_50퍼센트를_더한다() throws Exception {
        as("yuna", get("/api/stores/{s}/home/worker", store.getId()))
                .andExpect(jsonPath("$.monthlyPay.nightPay").value(0));
        as("owner", patch("/api/stores/{s}/settings", store.getId())
                .contentType("application/json").content("{\"fivePlusBusiness\":true}"))
                .andExpect(status().isOk());
        as("yuna", get("/api/stores/{s}/home/worker", store.getId()))
                .andExpect(jsonPath("$.monthlyPay.nightPay").value(4 * 10_000 / 2));
    }

    @Test
    void 공휴일과_알림함() throws Exception {
        as("yuna", get("/api/holidays").param("year", "2026"))
                .andExpect(jsonPath("$[?(@.date=='2026-09-25')].name").value("추석"));

        as("owner", post("/api/stores/{s}/notices", store.getId())
                .contentType("application/json").content("{\"title\":\"겨울 신메뉴 레시피\"}"))
                .andExpect(status().isOk());
        as("yuna", get("/api/users/me/notifications"))
                .andExpect(jsonPath("$.unreadCount").value(1))
                .andExpect(jsonPath("$.notifications[0].title").value("새 공지"))
                .andExpect(jsonPath("$.notifications[0].read").value(false));
        as("yuna", post("/api/users/me/notifications/read-all")).andExpect(status().isOk());
        as("yuna", get("/api/users/me/notifications")).andExpect(jsonPath("$.unreadCount").value(0));
        as("yuna", patch("/api/users/me/notification-settings")
                .contentType("application/json").content("{\"pushEnabled\":false}"))
                .andExpect(jsonPath("$.pushEnabled").value(false));
    }

    @Test
    void 근무자_목록은_직원_먼저_오늘_상태와_제출_여부를_보여준다() throws Exception {
        as("owner", get("/api/stores/{s}/roster", store.getId()))
                .andExpect(jsonPath("$.total").value(2))
                .andExpect(jsonPath("$.employees[0].name").value("지수"))
                .andExpect(jsonPath("$.employees[0].position").value("매니저"))
                .andExpect(jsonPath("$.employees[0].todayStatus").value("OFF"))
                .andExpect(jsonPath("$.employees[1].todayStatus").value("WORKING"))
                .andExpect(jsonPath("$.employees[1].todayStart").value("22:00:00"))
                .andExpect(jsonPath("$.employees[1].nextMonthSubmitted").value(false));
    }

    @Test
    void 역량_매칭은_시간대마다_조건을_채운_사람과_충족_여부를_보여준다() throws Exception {
        yuna.updatePermissions(List.of(EmployeePermission.STORE_KEY));
        windowRepository.save(new SkillWindowRequirement(store, "마감", LocalTime.of(22, 0), LocalTime.of(23, 0), null, null,
                EmployeePermission.STORE_KEY, 1, true, List.of()));
        windowRepository.save(new SkillWindowRequirement(store, "정산", LocalTime.of(22, 0), LocalTime.of(23, 0), null, null,
                EmployeePermission.CLOSING_SETTLEMENT, 1, true, List.of()));

        as("owner", get("/api/stores/{s}/skill-coverage", store.getId()))
                .andExpect(jsonPath("$[0].matchedNames[0]").value("유나"))
                .andExpect(jsonPath("$[0].satisfied").value(true))
                .andExpect(jsonPath("$[1].satisfied").value(false));
    }

    @Test
    void 내_정보_요약() throws Exception {
        as("yuna", get("/api/stores/{s}/me/summary", store.getId()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.monthDays").value(1))
                .andExpect(jsonPath("$.monthHours").value(4.0))
                .andExpect(jsonPath("$.storeName").value("운영매장"))
                .andExpect(jsonPath("$.pushEnabled").value(true));
    }

    private Employee employee(String username, String name, EmploymentType type) {
        Employee employee = new Employee(name, null, store, userRepository.save(new User(username, "pw", Role.EMPLOYEE)));
        employee.fillJoinProfile(null, null, false, type);
        employee.approve(10_000);
        return employeeRepository.save(employee);
    }

    private void schedule(Employee employee, LocalDate date, int startHour, int endHour) {
        Schedule schedule = new Schedule();
        schedule.setEmployee(employee);
        schedule.setStore(store);
        schedule.setWorkDate(date);
        schedule.setStartTime(LocalTime.of(startHour, 0));
        schedule.setEndTime(LocalTime.of(endHour, 0));
        scheduleRepository.save(schedule);
    }

    private ResultActions as(String username, MockHttpServletRequestBuilder request) throws Exception {
        return mockMvc.perform(request.header("Authorization", "Bearer " + jwtTokenProvider.createToken(username, "MANAGER")));
    }
}
