package com.example.store_scheduler_backend.domain;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

@Entity
@Getter
@NoArgsConstructor
public class Store {

    public static final int DEFAULT_CUSTOMERS_PER_STAFF = 30;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String name;

    private String address;

    // 기존 매장 데이터 때문에 null 허용, null은 기타로 본다
    @Enumerated(EnumType.STRING)
    private Industry industry;

    @Column(nullable = false, unique = true)
    private String storeCode;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "owner_id", nullable = false)
    private User owner;

    // true면 대신할 사람이 없어도 필수 휴무일에는 배정하지 않는다. 기존 매장 데이터 때문에 null 허용, null은 false로 본다
    private Boolean guaranteeMustDayOff;

    // 직원 1명이 한 교대에 감당할 수 있는 객수. 인력 제안 계산에 쓰고, null이면 기본값
    private Integer customersPerStaff;

    // true면 하루에 시간이 겹치지 않는 교대 2개까지 배정 (쪼개기 근무). null은 false로 본다
    private Boolean allowSplitShift;

    // 매달 이 날짜까지 다음 달 희망을 받는다. null이면 기본값
    private Integer preferenceDeadlineDay;

    // 연속 근무 한도(일). null이면 4일 (연속 5일 이상 금지)
    private Integer maxConsecutiveDays;

    // 상시 5인 이상 사업장이면 야간·연장 가산. null이면 승인된 직원 수로 판단
    private Boolean fivePlusBusiness;

    // 근무표 주기와 자동 생성. 자동 생성은 주기 시작 전 autoGenerateDaysBefore일, autoGenerateHour시에 후보안을 만든다
    @Enumerated(EnumType.STRING)
    private ScheduleCycle scheduleCycle;

    private Boolean autoGenerate;

    private Integer autoGenerateDaysBefore;

    private Integer autoGenerateHour;

    // 자동 생성에 실패한 기간 시작일. 매시간 같은 실패를 되풀이하지 않고 점주가 직접 생성하도록 한다
    private LocalDate autoGenerateFailedFor;

    // true면 법정 휴게시간(4시간 30분, 8시간 1시간)을 무급으로 보고 급여에서 뺀다. null은 false로 본다
    private Boolean deductBreakTime;

    @OneToMany(mappedBy = "store", cascade = CascadeType.ALL)
    private List<Employee> employees = new ArrayList<>();

    public Store(String name, String address, User owner, String storeCode) {
        this(name, address, null, owner, storeCode);
    }

    public Store(String name, String address, Industry industry, User owner, String storeCode) {
        this.name = name;
        this.address = address;
        this.industry = industry;
        this.owner = owner;
        this.storeCode = storeCode;
    }

    public Industry getIndustry() {
        return industry != null ? industry : Industry.ETC;
    }

    public void changeIndustry(Industry industry) {
        this.industry = industry;
    }

    public void updateInfo(String name, String address) {
        this.name = name;
        this.address = address;
    }

    public void reissueCode(String newCode) {
        this.storeCode = newCode;
    }

    public boolean isMustDayOffGuaranteed() {
        return Boolean.TRUE.equals(guaranteeMustDayOff);
    }

    public static final int DEFAULT_PREFERENCE_DEADLINE_DAY = 25;

    public boolean isSplitShiftAllowed() {
        return Boolean.TRUE.equals(allowSplitShift);
    }

    public int getPreferenceDeadlineDayOrDefault() {
        return preferenceDeadlineDay != null ? preferenceDeadlineDay : DEFAULT_PREFERENCE_DEADLINE_DAY;
    }

    public static final int DEFAULT_MAX_CONSECUTIVE_DAYS = 4;
    public static final int DEFAULT_AUTO_GENERATE_DAYS_BEFORE = 2;
    public static final int DEFAULT_AUTO_GENERATE_HOUR = 9;

    public int getMaxConsecutiveDaysOrDefault() {
        return maxConsecutiveDays != null ? maxConsecutiveDays : DEFAULT_MAX_CONSECUTIVE_DAYS;
    }

    public ScheduleCycle getScheduleCycleOrDefault() {
        return scheduleCycle != null ? scheduleCycle : ScheduleCycle.WEEKLY;
    }

    public boolean isAutoGenerate() {
        return Boolean.TRUE.equals(autoGenerate);
    }

    public int getAutoGenerateDaysBeforeOrDefault() {
        return autoGenerateDaysBefore != null ? autoGenerateDaysBefore : DEFAULT_AUTO_GENERATE_DAYS_BEFORE;
    }

    public int getAutoGenerateHourOrDefault() {
        return autoGenerateHour != null ? autoGenerateHour : DEFAULT_AUTO_GENERATE_HOUR;
    }

    // null인 항목은 바꾸지 않는다
    public void updateOperations(Integer maxConsecutiveDays, Boolean fivePlusBusiness, ScheduleCycle scheduleCycle,
                                 Boolean autoGenerate, Integer autoGenerateDaysBefore, Integer autoGenerateHour) {
        if (maxConsecutiveDays != null) this.maxConsecutiveDays = maxConsecutiveDays;
        if (fivePlusBusiness != null) this.fivePlusBusiness = fivePlusBusiness;
        if (scheduleCycle != null) this.scheduleCycle = scheduleCycle;
        if (autoGenerate != null) this.autoGenerate = autoGenerate;
        if (autoGenerateDaysBefore != null) this.autoGenerateDaysBefore = autoGenerateDaysBefore;
        if (autoGenerateHour != null) this.autoGenerateHour = autoGenerateHour;
    }

    public boolean isBreakTimeDeducted() {
        return Boolean.TRUE.equals(deductBreakTime);
    }

    public void updateBreakDeduction(boolean deductBreakTime) {
        this.deductBreakTime = deductBreakTime;
    }

    public void markAutoGenerateFailed(LocalDate periodStart) {
        this.autoGenerateFailedFor = periodStart;
    }

    public int getCustomersPerStaffOrDefault() {
        return customersPerStaff != null ? customersPerStaff : DEFAULT_CUSTOMERS_PER_STAFF;
    }

    // null인 항목은 바꾸지 않는다
    public void updateSettings(Boolean guaranteeMustDayOff, Integer customersPerStaff) {
        updateSettings(guaranteeMustDayOff, customersPerStaff, null, null);
    }

    public void updateSettings(Boolean guaranteeMustDayOff, Integer customersPerStaff, Boolean allowSplitShift,
                               Integer preferenceDeadlineDay) {
        if (guaranteeMustDayOff != null) this.guaranteeMustDayOff = guaranteeMustDayOff;
        if (customersPerStaff != null) this.customersPerStaff = customersPerStaff;
        if (allowSplitShift != null) this.allowSplitShift = allowSplitShift;
        if (preferenceDeadlineDay != null) this.preferenceDeadlineDay = preferenceDeadlineDay;
    }
}