package com.example.store_scheduler_backend.service;

import com.example.store_scheduler_backend.domain.ScheduleCycle;
import com.example.store_scheduler_backend.domain.Store;
import com.example.store_scheduler_backend.repository.ScheduleProposalRepository;
import com.example.store_scheduler_backend.repository.StoreRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.YearMonth;
import java.time.temporal.TemporalAdjusters;

// 매장 근무표 주기: 다음 기간, 자동 생성 시각, 희망 제출 마감
@Service
@Transactional(readOnly = true)
@RequiredArgsConstructor
public class SchedulePlanService {

    // 자동 생성일 며칠 전까지 희망을 받는지
    public static final int DEADLINE_DAYS_BEFORE_GENERATION = 3;

    private final StoreRepository storeRepository;
    private final ScheduleProposalRepository proposalRepository;
    private final StoreAccessGuard storeAccessGuard;
    private final ScheduleAutomationService automationService;
    private final FcmService fcmService;

    public record Plan(ScheduleCycle cycle, LocalDate periodStart, LocalDate periodEnd, boolean autoGenerate,
                       LocalDateTime generateAt, LocalDate preferenceDeadline) {
    }

    public Plan getPlan(Long storeId, LocalDate today, String username) {
        Store store = storeAccessGuard.verifyMember(storeId, username);
        return planOf(store, today);
    }

    public static Plan planOf(Store store, LocalDate today) {
        ScheduleCycle cycle = store.getScheduleCycleOrDefault();
        LocalDate start = nextPeriodStart(cycle, today);
        LocalDate end = switch (cycle) {
            case WEEKLY -> start.plusDays(6);
            case BIWEEKLY -> start.plusDays(13);
            case MONTHLY -> YearMonth.from(start).atEndOfMonth();
        };
        LocalDateTime generateAt = start.minusDays(store.getAutoGenerateDaysBeforeOrDefault())
                .atTime(store.getAutoGenerateHourOrDefault(), 0);
        LocalDate deadline = store.isAutoGenerate()
                ? generateAt.toLocalDate().minusDays(DEADLINE_DAYS_BEFORE_GENERATION)
                : cycle == ScheduleCycle.MONTHLY ? PreferenceService.deadlineOf(store, YearMonth.from(start)) : start.minusDays(1);
        return new Plan(cycle, start, end, store.isAutoGenerate(), generateAt, deadline);
    }

    static LocalDate nextPeriodStart(ScheduleCycle cycle, LocalDate today) {
        return cycle == ScheduleCycle.MONTHLY
                ? YearMonth.from(today).plusMonths(1).atDay(1)
                : today.with(TemporalAdjusters.next(DayOfWeek.MONDAY));
    }

    // 자동 생성 시각이 지났고 그 기간 후보안이 아직 없으면 만든다. 만든 매장 수를 돌려준다
    @Transactional
    public int generateDue(LocalDateTime now) {
        int generated = 0;
        for (Store store : storeRepository.findByAutoGenerateTrue()) {
            Plan plan = planOf(store, now.toLocalDate());
            if (now.isBefore(plan.generateAt()) || proposalRepository.existsByStoreIdAndWeekStart(store.getId(), plan.periodStart())) {
                continue;
            }
            String owner = store.getOwner().getUsername();
            try {
                switch (plan.cycle()) {
                    case WEEKLY -> automationService.generateProposal(store.getId(), plan.periodStart(), owner);
                    case BIWEEKLY -> automationService.generateBiweeklyProposal(store.getId(), plan.periodStart(), owner);
                    case MONTHLY -> automationService.generateMonthlyProposal(store.getId(), YearMonth.from(plan.periodStart()), owner);
                }
                fcmService.send(store.getOwner(), "근무표 3안이 준비됐어요",
                        plan.periodStart() + "부터의 근무표 후보안을 비교하고 확정해주세요.");
                generated++;
            } catch (IllegalArgumentException e) {
                // 직원이나 교대가 없는 매장은 건너뛴다
                fcmService.send(store.getOwner(), "근무표 자동 생성 실패", e.getMessage());
            }
        }
        return generated;
    }
}
